"""Generate src/data/products.js from backend/server.py PRODUCTS_DATA.

The backend stays the single source of truth for product content (it also
builds the catalog PDF). This script adds stable URL slugs and local WebP
image names for the static website. Re-run after editing PRODUCTS_DATA:

    python3 -I scripts/export-products.py
"""
import ast
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SERVER = ROOT.parent / "backend" / "server.py"
OUT = ROOT / "src" / "data" / "products.js"

# Backend category name -> URL slug
CATEGORY_SLUGS = {
    "Armoured Cable": "armoured-cable",
    "Electric House Wire": "house-wire",
    "Flexible Cable": "flexible-cable",
    "CCTV Cables": "cctv-cable",
    "Submersible Cable": "submersible-cable",
    "Copper Wire": "copper-wire",
    "CAT6 & LAN Cables": "cat6-lan-cable",
    "Telephone & Communication Cable": "telephone-cable",
}

# Remote source image id -> local WebP basename (see scripts/fetch-images.mjs)
IMAGE_NAMES = {
    "68e49c9aed06f3bbb445df55": "armoured-cable",
    "68e49bf05c295f6c8beebf4e": "armoured-cable-3-core",
    "68e4995b1a14f21bee4f1cc3": "armoured-cable-4-core",
    "68e49a12b575d00c5aa771b6": "copper-armoured-cable",
    "68e4a0060b69274f568853d8": "flexible-cable",
    "68e4a12956522870096e857a": "house-wire",
    "68e49f18993a511b693b1be0": "cctv-cable",
    "68e60002327a323aaf2eb218": "submersible-cable",
}


def slugify(name: str) -> str:
    s = name.lower().replace("+", " plus ").replace("&", " and ")
    s = re.sub(r"[^a-z0-9]+", "-", s)
    return s.strip("-")


def main() -> None:
    tree = ast.parse(SERVER.read_text())
    data = None
    for node in tree.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", None) == "PRODUCTS_DATA":
            data = ast.literal_eval(node.value)
    if data is None:
        raise SystemExit("PRODUCTS_DATA not found in backend/server.py")

    products, seen = [], set()
    for p in data:
        slug = slugify(p["name"])
        if slug in seen:
            raise SystemExit(f"Duplicate slug: {slug}")
        seen.add(slug)
        image_id = Path(p["image"]).stem
        if image_id not in IMAGE_NAMES:
            raise SystemExit(f"No local image for {p['name']} ({p['image']}) — add it to fetch-images.mjs and IMAGE_NAMES")
        products.append({
            "slug": slug,
            "name": p["name"],
            "category": p["category"],
            "categorySlug": CATEGORY_SLUGS[p["category"]],
            "description": p["description"],
            "features": p["features"],
            "specs": p["specs"],
            "image": IMAGE_NAMES[image_id],
        })

    OUT.write_text(
        "// AUTO-GENERATED by scripts/export-products.py from backend/server.py — do not edit by hand.\n"
        f"export const products = {json.dumps(products, indent=2, ensure_ascii=False)};\n"
    )
    print(f"Wrote {len(products)} products to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
